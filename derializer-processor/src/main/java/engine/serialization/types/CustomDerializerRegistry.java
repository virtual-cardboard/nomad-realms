package engine.serialization.types;

import java.util.HashMap;
import java.util.Map;
import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.TypeElement;
import engine.serialization.Derializable;

/**
 * Registry of hand-written serializers, mapping each target type to the class implementing
 * {@code Derializer<T>}. Custom serializers stay opaque leaf values in generated code; they do not take
 * part in identity tracking.
 *
 * @author Lunkle
 */
public class CustomDerializerRegistry {

	/** Target type qualified name to the class implementing Derializer for it. */
	private final Map<String, TypeElement> serializers = new HashMap<>();

	private ProcessingEnvironment env;

	public void init(ProcessingEnvironment env) {
		this.env = env;
	}

	/** @return true if the given target type already has a registered custom serializer */
	public boolean hasCustomSerializer(String targetFQCN) {
		return serializers.containsKey(targetFQCN);
	}

	/** @return the registered custom serializer for the given target type, or null if none */
	public TypeElement existingSerializer(String targetFQCN) {
		return serializers.get(targetFQCN);
	}

	public void put(String targetFQCN, TypeElement serializerElement) {
		serializers.put(targetFQCN, serializerElement);
	}

	public boolean hasCustomSerializer(TypeElement target) {
		return serializers.containsKey(target.getQualifiedName().toString());
	}

	/**
	 * Returns true for types whose serializer is generated by this processor; types with a custom serializer
	 * are not generated.
	 */
	public boolean isGenerated(TypeElement target) {
		return target.getAnnotation(Derializable.class) != null && !hasCustomSerializer(target);
	}

	/** @return the qualified name of the serializer class emitted or registered for the given target type */
	public String serializerFQCN(TypeElement target) {
		TypeElement customDerializer = serializers.get(target.getQualifiedName().toString());
		if (customDerializer != null) {
			return customDerializer.getQualifiedName().toString();
		}
		String packageName = env.getElementUtils().getPackageOf(target).getQualifiedName().toString();
		return packageName + "." + target.getSimpleName() + "Derializer";
	}

	/** @return the simple name of the serializer class emitted or registered for the given target type */
	public String serializerSimpleName(TypeElement target) {
		TypeElement customDerializer = serializers.get(target.getQualifiedName().toString());
		if (customDerializer != null) {
			return customDerializer.getSimpleName().toString();
		}
		return target.getSimpleName() + "Derializer";
	}

}
